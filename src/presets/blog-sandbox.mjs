export function blogSandboxPreset(options = {}) {
  return terminal => {
    const fs = terminal.fs;
    const user = options.user || terminal.user;
    const group = options.group || user;
    const blogRoot = options.blogRoot || `/home/${user}/blog`;

    terminal.hostname = options.hostname || terminal.hostname;
    terminal.aliases.ll ||= 'ls -al';
    terminal.aliases.la ||= 'ls -a';
    terminal.aliases.grep ||= 'grep --color=auto';

    fs.ensureDir(blogRoot, { owner: user, group });
    fs.addFile(`/home/${user}/.bashrc`, 'alias ll="ls -al"\nalias la="ls -a"\nexport EDITOR=vim\n', { owner: user, group, perm: '-rw-r--r--' });
    fs.addFile(`/home/${user}/.profile`, '[[ -f ~/.bashrc ]] && . ~/.bashrc\n', { owner: user, group, perm: '-rw-r--r--' });
    fs.addFile(`/home/${user}/.bash_history`, 'ls -la\ncat /etc/os-release\njournalctl -n 5\nsudo -l\n', { owner: user, group, perm: '-rw-------' });
    fs.addFile(`${blogRoot}/README.md`, '# Blog workspace\n\nThis directory is generated by the blog-sandbox preset.\n', { owner: user, group });
    fs.addFile(`${blogRoot}/flag.txt`, 'The real flag is not here. Keep exploring.\n', { owner: user, group, perm: '-rw-r--r--' });

    fs.addFile('/etc/motd', 'Welcome to the Blog Terminal Sandbox.\nAll commands run in an isolated frontend VFS.\n');
    fs.addFile('/etc/hosts', '127.0.0.1 localhost\n127.0.1.1 blog-server\n10.0.2.15 blog-server.internal\n');
    fs.addFile('/var/log/syslog', 'May 08 10:01:01 blog-server systemd[1]: Started static blog service.\nMay 08 10:01:02 blog-server nginx[901]: GET / 200\n');
    fs.addFile('/var/log/auth.log', 'May 08 10:02:01 blog-server sudo: guest : command not allowed ; TTY=pts/0 ; PWD=/home/guest ; USER=root ; COMMAND=/bin/cat /etc/shadow\n', { owner: 'root', group: 'adm', perm: '-rw-r-----' });
    fs.addFile('/root/flag.txt', options.rootFlag || 'FLAG{replace_this_in_your_site_preset}\n', { owner: 'root', group: 'root', perm: '-rw-------' });
  };
}
